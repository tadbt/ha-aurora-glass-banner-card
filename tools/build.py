"""Builds aurora-glass-banner-card.js from src/.

  python3 tools/build.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PARTS = [
    "disegno.js",
    "mondi-base.js",
    "mondi-a.js",
    "mondi-b.js",
    "effetti.js",
    "lingua.js",
]
VERSION = "1.1.2"


def bundle() -> str:
    out = f"/* Aurora Glass Banner Card v{VERSION} — Home Assistant Lovelace Card (generated by tools/build.py) */\n"
    for p in PARTS:
        out += f"\n/* ---- {p} ---- */\n" + (SRC / "js" / p).read_text(encoding="utf-8") + "\n"
    card = (SRC / "card.js").read_text(encoding="utf-8").replace("__VERSION__", json.dumps(VERSION))
    return out + "\n/* ---- card.js ---- */\n" + card


def main() -> None:
    js = bundle()
    root_out = ROOT / "aurora-glass-banner-card.js"
    root_out.write_text(js, encoding="utf-8", newline="\n")

    dist_dir = ROOT / "dist"
    dist_dir.mkdir(exist_ok=True)
    (dist_dir / "aurora-glass-banner-card.js").write_text(js, encoding="utf-8", newline="\n")

    size = root_out.stat().st_size // 1024
    print(f"Aurora Glass Banner Card v{VERSION}: {size} KB -> {root_out.name}")


if __name__ == "__main__":
    main()
